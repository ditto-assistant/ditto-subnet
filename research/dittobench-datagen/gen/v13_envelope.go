// Bench v13 memory envelope (issues #1848 / #1529).
//
// v8 through v12 sized the memory suite as a primary budget with carve-outs:
// every new family (v10 programs, v12 divergence, v12 family compiler) was
// subtracted from a residual world-question pool, and the world pool itself
// took every story oracle before filling with ordinary questions. That residual
// arithmetic is how monetary claims came to own 50.9% of the v12 memory score
// weight: four of the seven story oracles, the whole program catalog, the whole
// family compiler, and the project-outstanding oracle are all money.
//
// v13 replaces the residual with a PUBLISHED SLOT TABLE. Every slot has a fixed
// count per run size, the counts sum to the memory envelope, and each slot is
// filled by exactly one generator. The table is the contract; a generator
// change that moves a count is a new contract, not a drift.
//
// All dedicated v13 generators are integrated. The interim registries are
// empty, so TestV13MixAuditGateAcrossFortySeeds enforces the complete gate.

// V13MemoryEnvelope is the memory-case slot table for one v13 run size.
type V13MemoryEnvelope struct {
	// Story is the deep three-record story programs (six oracles per arc).
	Story int
	// OrdinaryWorld is the person / project / trip questions, with the
	// monetary project-outstanding oracle capped at OrdinaryProjectOutstandingCap.
	OrdinaryWorld int
	// BusinessPrograms is the semantic business-event open-program catalog.
	BusinessPrograms int
	// PersonalPrograms is the personal-life event programs (#1838).
	PersonalPrograms int
	// Abstention is the evidence-bounded abstention family (#1530).
	Abstention int
	// RecordQuantity is the record-determined quantity family (#1837).
	RecordQuantity int
	// Divergence is the parser-divergence canary family (gen/divergence.go).
	Divergence int
	// PointInTime is the same-turn correction / point-in-time twins (#1844).
	PointInTime int
	// Integrity is the world-native conversational and integrity tail:
	// 3 chitchat, 3 declarative acknowledgement, 3 declarative behaviour,
	// 1 canary, 4 injection.
	Integrity int
	// Isolation is the read-only cross-user graph isolation cases
	// (gen/isolation.go); generated by the pipeline, counted here so the table
	// sums to the public memory envelope.
	Isolation int
}

// Total is the number of memory cases the envelope publishes.
func (e V13MemoryEnvelope) Total() int {
	return e.Story + e.OrdinaryWorld + e.BusinessPrograms + e.PersonalPrograms + e.Abstention +
		e.RecordQuantity + e.Divergence + e.PointInTime + e.Integrity + e.Isolation
}

// Interim is the number of cases currently filled by the interim world fill.
func (e V13MemoryEnvelope) Interim() int {
	total := 0
	for _, slot := range v13InterimSlots {
		total += e.slot(slot)
	}
	return total
}

func (e V13MemoryEnvelope) slot(name string) int {
	switch name {
	case V13SlotStory:
		return e.Story
	case V13SlotOrdinaryWorld:
		return e.OrdinaryWorld
	case V13SlotBusinessPrograms:
		return e.BusinessPrograms
	case V13SlotPersonalPrograms:
		return e.PersonalPrograms
	case V13SlotAbstention:
		return e.Abstention
	case V13SlotRecordQuantity:
		return e.RecordQuantity
	case V13SlotDivergence:
		return e.Divergence
	case V13SlotPointInTime:
		return e.PointInTime
	case V13SlotIntegrity:
		return e.Integrity
	case V13SlotIsolation:
		return e.Isolation
	}
	return 0
}

// Slot names, shared by the envelope, the mix audit, and the tests.
const (
	V13SlotStory            = "story"
	V13SlotOrdinaryWorld    = "ordinary-world"
	V13SlotBusinessPrograms = "business-programs"
	V13SlotPersonalPrograms = "personal-programs"
	V13SlotAbstention       = "abstention"
	V13SlotRecordQuantity   = "record-quantity"
	V13SlotDivergence       = "divergence"
	V13SlotPointInTime      = "point-in-time"
	V13SlotIntegrity        = "integrity"
	V13SlotIsolation        = "isolation"
)

// V13SlotOrder is the published slot order for reports.
var V13SlotOrder = []string{
	V13SlotStory, V13SlotOrdinaryWorld, V13SlotBusinessPrograms, V13SlotPersonalPrograms,
	V13SlotAbstention, V13SlotRecordQuantity, V13SlotDivergence, V13SlotPointInTime,
	V13SlotIntegrity, V13SlotIsolation,
}

// v13InterimSlots are the slots whose dedicated generator has not landed. Remove
// a slot from this list in the same change that wires its generator into
// generateV13WorldMemorySuite; TestV13InterimSlotsArePinned keeps the list
// honest and TestV13MixAuditGateAcrossFortySeeds arms the full #1529 gate once
// it is empty.
var v13InterimSlots = []string{}

// V13InterimSlots returns the interim slot names (copy).
func V13InterimSlots() []string { return append([]string(nil), v13InterimSlots...) }

// v13InterimGenerators are the slots that already have a dedicated count but
// are still filled by a monetary v12-era generator: business programs
// (universe.GenerateV12Programs until #1520), record-determined quantity
// (buildFamilyCompiler until #1837), and the story oracle set (#1841 replaces
// the two pure-money oracles kept per arc). Remove a slot here in the same
// change that swaps its generator. The #1529 gate stays informational while
// either this list or v13InterimSlots is non-empty, so landing the three interim
// slots before the monetary swaps cannot turn the gate fatal-red on a mix that
// is known to violate the money caps.
var v13InterimGenerators = []string{}

// V13InterimGenerators returns the slots still filled by an interim monetary
// generator (copy).
func V13InterimGenerators() []string { return append([]string(nil), v13InterimGenerators...) }

// V13InterimPending reports whether any interim slot or interim generator
// remains: the condition under which the full #1529 gate is informational.
func V13InterimPending() bool { return len(v13InterimSlots) > 0 || len(v13InterimGenerators) > 0 }

// V13OrdinaryProjectOutstandingCap bounds the monetary project-outstanding
// oracle inside the ordinary-world slot (issue #1848: "project-outstanding <= 4").
// Temporal invoice twins add eight monetary cases to the assembled mix.
// Together with ten compiler and at most three story cases, one ordinary
// invoice leaves the full run inside the published 22-case hard ceiling.
const V13OrdinaryProjectOutstandingCap = 1

// v13StoryOraclesPerArc is the number of story oracles kept per arc (78 = 13 x 6
// on the full profile).
const v13StoryOraclesPerArc = 6

// V13FullEnvelope is the published 250-case full-profile table.
var V13FullEnvelope = V13MemoryEnvelope{
	Story: 78, OrdinaryWorld: 32, BusinessPrograms: 28, PersonalPrograms: 24, Abstention: 25,
	RecordQuantity: 16, Divergence: 12, PointInTime: 12, Integrity: 14, Isolation: 9,
}

// v13MediumEnvelope keeps the v12 medium memory total (95) at v13 proportions.
// Six story arcs x six oracles, program counts stay multiples of four.
var v13MediumEnvelope = V13MemoryEnvelope{
	Story: 36, OrdinaryWorld: 12, BusinessPrograms: 4, PersonalPrograms: 4, Abstention: 8,
	RecordQuantity: 4, Divergence: 4, PointInTime: 4, Integrity: 14, Isolation: 5,
}

// v13SmallEnvelope is the smoke profile: one story arc, a handful of ordinary
// questions, one program group, and the integrity tail (three injection probes:
// the scale-1 world has only three projects).
var v13SmallEnvelope = V13MemoryEnvelope{
	Story: 6, OrdinaryWorld: 4, BusinessPrograms: 4, PersonalPrograms: 0, Abstention: 0,
	RecordQuantity: 0, Divergence: 0, PointInTime: 0, Integrity: 13, Isolation: 0,
}

// v13EnvelopeFor maps Profile.Mem to its slot table. Only the three public run
// sizes are contracts; any other size fails closed rather than inventing a
// table.
func v13EnvelopeFor(mem int) (V13MemoryEnvelope, bool) {
	switch mem {
	case profilesV13["full"].Mem:
		return V13FullEnvelope, true
	case profilesV13["medium"].Mem:
		return v13MediumEnvelope, true
	case profilesV13["small"].Mem:
		return v13SmallEnvelope, true
	default:
		return V13MemoryEnvelope{}, false
	}
}

// V13EnvelopeForRunSize is the public accessor for audits and tests.
func V13EnvelopeForRunSize(runSize string) (V13MemoryEnvelope, bool) {
	prof, ok := profilesV13[runSize]
	if !ok {
		return V13MemoryEnvelope{}, false
	}
	return v13EnvelopeFor(prof.Mem)
}

// worldPlanSelection is the world-question budget the envelope hands to
// universe.World.SelectQuestionPlans: the story slot, the capped ordinary slot,
// and the interim fill for slots without a generator.
func (e V13MemoryEnvelope) worldPlanSelection() universe.WorldPlanSelection {
	return universe.WorldPlanSelection{
		StoryPerArc:  v13StoryOraclesPerArc,
		Ordinary:     e.OrdinaryWorld,
		OrdinaryCaps: map[string]int{"project-outstanding": V13OrdinaryProjectOutstandingCap},
		Interim:      e.Interim(),
		Salt:         "v13",
	}
}

// generateV13WorldMemorySuite fills the published v13 slot table. It shares the
// v8 coherent world, the v12 program / divergence / family-compiler generators,
// and the integrity tail with the v12 path, but every count comes from
// V13MemoryEnvelope rather than from a residual budget. The isolation slot is added by
// the pipeline (GenerateIsolationForVersion) exactly as before.
func generateV13WorldMemorySuite(seed int64, n, nWaves, benchVersion int) (MemorySuite, error) {
	return generateV13WorldMemorySuiteWithFacts(context.Background(), seed, n, nWaves, benchVersion, 0, nil)
}

func generateV13WorldMemorySuiteWithFacts(ctx context.Context, seed int64, n, nWaves, benchVersion int, presentationSeed int64, renderer universe.V13FactRenderer) (MemorySuite, error) {
	if nWaves < 1 {
		nWaves = 1
	}
	envelope, ok := v13EnvelopeFor(n)
	if !ok {
		return MemorySuite{}, fmt.Errorf("v13 memory envelope: no slot table for %d memory cases", n)
	}
	scale, _ := v8WorldProfile(n)
	world := universe.GenerateForVersion(seed, scale, benchVersion)
	if renderer != nil {
		documents, ok := renderer.(universe.V13FactDocumentRenderer)
		if !ok {
			return MemorySuite{}, fmt.Errorf("v13 fact world: story renderer required")
		}
		if err := world.RenderV13FactStories(ctx, documents); err != nil {
			return MemorySuite{}, err
		}
		if err := world.RenderV13FactOrdinaryWorld(ctx, documents); err != nil {
			return MemorySuite{}, err
		}
		if err := world.RenderV13FactBusinessImport(ctx, documents); err != nil {
			return MemorySuite{}, err
		}
	}
	allocation := world.V13Allocation(envelope.Isolation)
	decision, err := buildV13Abstention(seed, n, world, allocation, benchVersion)
	if err != nil {
		return MemorySuite{}, err
	}
	temporal, err := buildV13PointInTime(seed, world, allocation, benchVersion)
	if err != nil {
		return MemorySuite{}, err
	}
	if len(decision) != envelope.Abstention || 2*len(temporal) != envelope.PointInTime {
		return MemorySuite{}, fmt.Errorf("v13 temporal budget mismatch: absence %d/%d, as-of %d/%d", len(decision), envelope.Abstention, 2*len(temporal), envelope.PointInTime)
	}
	selection := envelope.worldPlanSelection()
	selection.Exclude = allocation.ExcludeKeys()
	selection.Require = allocation.StagedQuestionKeys()
	staged := world.StagedCorrectionWaves(allocation, nWaves)
	// Answerable decision twins occupy the ordinary-world slot, not an
	// unreported extra case budget.
	selection.Ordinary -= len(decision)
	if selection.Ordinary < 0 {
		return MemorySuite{}, fmt.Errorf("v13 answerable twins exceed ordinary-world budget")
	}
	plans, counts, err := world.SelectQuestionPlans(selection)
	if err != nil {
		return MemorySuite{}, err
	}
	var business []universe.V10GeneratedCase
	if renderer != nil {
		business, err = universe.GenerateV13RenderedFactPrograms(ctx, seed, presentationSeed, envelope.BusinessPrograms, renderer)
	} else {
		business, err = universe.GenerateV13Programs(seed, envelope.BusinessPrograms)
	}
	if err != nil {
		return MemorySuite{}, err
	}
	var personal []universe.V10GeneratedCase
	if envelope.PersonalPrograms > 0 {
		if renderer != nil {
			personal, err = universe.GenerateV13RenderedPersonalFactPrograms(ctx, seed, presentationSeed, envelope.PersonalPrograms, renderer)
		} else {
			personal, err = universe.GenerateV13PersonalPrograms(seed, envelope.PersonalPrograms)
		}
		if err != nil {
			return MemorySuite{}, err
		}
	}
	integrity := v8WorldIntegrityCases(seed, world, benchVersion)
	var injectionPairs []protocol.MemoryPair
	if envelope.Integrity == 14 {
		injection, err := BuildV13WorldInjection(seed, world)
		if err != nil {
			return MemorySuite{}, err
		}
		integrity = append(integrity[:v8WorldConversationalCaseCount+v8WorldCanaryCaseCount], injection.Cases...)
		injectionPairs = injection.Pairs
	}
	suite := MemorySuite{
		SeedingWaves: nWaves, ConversationalCases: v8WorldConversationalCaseCount,
		StoredInstructionCases: len(integrity) - v8WorldConversationalCaseCount - v8WorldCanaryCaseCount,
		Waves:                  make([]protocol.SeedRequest, nWaves),
		V13Slots: map[string]int{
			V13SlotStory: counts.Story, V13SlotOrdinaryWorld: counts.Ordinary + len(decision),
			V13SlotBusinessPrograms: len(business), V13SlotPersonalPrograms: len(personal),
			V13SlotAbstention: len(decision), V13SlotPointInTime: 2 * len(temporal),
			V13SlotIntegrity: len(integrity), V13SlotIsolation: envelope.Isolation,
		},
		AbstentionCases: len(decision), PointInTimeCases: 2 * len(temporal),
	}
	if renderer != nil {
		suite.FactWorldPairs = append([]protocol.MemoryPair(nil), world.Pairs...)
	}
	for i := range suite.Waves {
		suite.Waves[i] = protocol.SeedRequest{UserID: PrimaryUser, Wave: i}
		suite.Waves[i].Pairs = world.StagedPairs(staged, i)
	}
	for _, plan := range plans {
		plan.Case.BenchVersion = benchVersion
		plan.Case.WritingProtected = append([]string(nil), plan.Constraints...)
		suite.Cases = append(suite.Cases, StagedCase{Case: plan.Case, RequiredPairIDs: append([]string(nil), plan.RequiredPairIDs...)})
	}
	for _, generated := range append(business, personal...) {
		provenance := generated.Provenance
		suite.Cases = append(suite.Cases, StagedCase{Case: generated.Plan.Case,
			RequiredPairIDs: append([]string(nil), generated.Plan.RequiredPairIDs...), V10Provenance: &provenance})
		suite.Waves[0].Pairs = append(suite.Waves[0].Pairs, generated.Pairs...)
	}
	suite.Cases = append(suite.Cases, integrity...)
	suite.Waves[0].Pairs = append(suite.Waves[0].Pairs, injectionPairs...)
	if envelope.Divergence > 0 {
		cases, pairs, sources := buildParserDivergenceSources(seed, envelope.Divergence, benchVersion)
		if renderer != nil {
			documents, ok := renderer.(universe.V13FactDocumentRenderer)
			if !ok {
				return MemorySuite{}, fmt.Errorf("v13 fact divergence: document renderer required")
			}
			pairs, err = renderDivergenceFacts(ctx, cases, pairs, sources, documents)
			if err != nil {
				return MemorySuite{}, err
			}
		}
		for i := range cases {
			cases[i].Case.BenchVersion = benchVersion
		}
		suite.Cases = append(suite.Cases, cases...)
		suite.Waves[0].Pairs = append(suite.Waves[0].Pairs, pairs...)
		suite.ParserDivergenceCases = len(cases)
		suite.V13Slots[V13SlotDivergence] = len(cases)
	}
	families := BuildFamilyCompilerV13(seed, envelope.RecordQuantity)
	if renderer != nil {
		documents, ok := renderer.(universe.V13FactDocumentRenderer)
		if !ok {
			return MemorySuite{}, fmt.Errorf("v13 fact quantity: document renderer required")
		}
		families, err = renderQuantityFacts(ctx, families, documents)
		if err != nil {
			return MemorySuite{}, err
		}
	}
	for _, family := range families {
		suite.Cases = append(suite.Cases, family.Staged)
		suite.Waves[0].Pairs = append(suite.Waves[0].Pairs, family.Pairs...)
		suite.FamilyCompilerCases++
	}
	suite.V13Slots[V13SlotRecordQuantity] = suite.FamilyCompilerCases
	suite.Cases = placeV13TwinPairs(seed, suite.Cases, append(decision, temporal...))
	for i := range suite.Cases {
		for _, id := range suite.Cases[i].RequiredPairIDs {
			if wave, ok := staged[id]; ok {
				if wave > suite.Cases[i].RunAfterWave {
					suite.Cases[i].RunAfterWave = wave
				}
			}
		}
		if suite.Cases[i].RunAfterWave > 0 {
			suite.StagedCorrectionCases++
		}
	}
	suite.WorldCases = len(suite.Cases) - suite.ConversationalCases
	if len(suite.Cases)+envelope.Isolation != envelope.Total() {
		return MemorySuite{}, fmt.Errorf("v13 memory budget: %d plus %d isolation, want %d", len(suite.Cases), envelope.Isolation, envelope.Total())
	}
	// v13 writing noise is applied once by the salted artifact surface pass.
	return suite, nil
}
