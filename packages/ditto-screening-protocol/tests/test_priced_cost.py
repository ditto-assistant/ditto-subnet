"""The priced cost mirror reproduces the Go contract's vectors bit for bit.

The vectors are generated by ``services/dittobench-api`` (``go test
./internal/scoregates -run TestPricedCostVectorsGolden -update-priced-cost``)
and read here from the monorepo, so a Go change that moves them fails this test
until the mirror moves too.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

from ditto_screening_protocol.priced_cost import (
    PRICED_COST_CONTRACT_ID,
    PRICED_COST_MIN_BENCH_VERSION,
    PricedCostReport,
    build_priced_cost,
    is_priced_cost_bench_version,
    priced_cost_factor_bps,
)

_MONOREPO_ROOT = Path(__file__).resolve().parents[3]
_VECTORS = (
    _MONOREPO_ROOT
    / "services/dittobench-api/internal/scoregates/testdata/priced_cost_vectors.json"
)


def _vectors() -> dict[str, Any]:
    return json.loads(_VECTORS.read_text(encoding="utf-8"))


def test_contract_id_matches_go() -> None:
    assert _vectors()["contract_id"] == PRICED_COST_CONTRACT_ID


@pytest.mark.parametrize("vector", _vectors()["vectors"], ids=lambda v: v["name"])
def test_build_matches_go_vector(vector: dict[str, Any]) -> None:
    usage = vector["usage"]
    got = build_priced_cost(
        bench_version=vector["bench_version"],
        posture=vector["posture"],
        cases=vector["cases"],
        chat_complete=vector["chat_complete"],
        source=vector["source"],
        **usage,
    )
    assert got == vector["summary"]
    report = PricedCostReport.model_validate(vector["summary"])
    assert report.matches_published_rule(vector["bench_version"])


def test_curve_matches_go_points() -> None:
    for point in _vectors()["factors"]:
        assert priced_cost_factor_bps(point["ratio_bps"]) == point["factor_bps"]


def test_version_floor() -> None:
    assert not is_priced_cost_bench_version(PRICED_COST_MIN_BENCH_VERSION - 1)
    assert is_priced_cost_bench_version(PRICED_COST_MIN_BENCH_VERSION)
    assert is_priced_cost_bench_version(PRICED_COST_MIN_BENCH_VERSION + 5)
    assert (
        build_priced_cost(
            bench_version=15,
            posture="enforce",
            cases=350,
            chat_complete=True,
            source="relay",
        )
        is None
    )


@pytest.mark.parametrize(
    "change",
    [
        {"applied_factor_bps": 10_000, "factor_bps": 10_000},
        {"contract_id": "priced-cost-v0"},
        {"window": "datagen_half"},
        {"normalization_cases": 351},
        {"reference_nano_usd": 2_000_000_000},
        {"floor_bps": 0},
        {"prompt_cost_nano_usd": 1},
        {"completion_cost_nano_usd": 1},
        {"embedding_cost_nano_usd": 1},
        {"decision_cost_nano_usd": 1},
        {"prices": {"prompt_token": 1}},
        {"curve": [{"ratio_bps": 10_000, "factor_bps": 10_000}]},
        {"prompt_tokens": 9_007_199_254_740_992},
    ],
    ids=lambda change: "+".join(change),
)
def test_tampered_terms_are_detected(change: dict[str, Any]) -> None:
    vector = next(v for v in _vectors()["vectors"] if v["name"] == "v15_full_catalog")
    tampered = dict(vector["summary"], **change)
    assert not PricedCostReport.model_validate(tampered).matches_published_rule(16)


def test_priced_result_on_zero_cases_is_detected() -> None:
    vector = next(v for v in _vectors()["vectors"] if v["name"] == "zero_cases")
    tampered = dict(vector["summary"], result="priced")
    assert not PricedCostReport.model_validate(tampered).matches_published_rule(16)
