def _load(name: str) -> dict[str, Any]:
    return json.loads((_TESTDATA / name).read_text())


def _bits(x: float) -> bytes:
    return struct.pack(">d", x)


def test_contract_constants() -> None:
    assert DUELING_MIN_BENCH_VERSION == 16
    assert DUELING_SLICE_COLUMNS == 5
    assert DUELING_SLICE_CASES_PER_COLUMN == 35
    assert DUELING_COLUMN_WEIGHT * DUELING_SLICE_COLUMNS == 0.5
    assert DUELING_SLICE_CONTRACT == "dittobench-dueling-slice/v1"
    assert DUELING_SLICE_MODE == "dueling-slice-v1"


def test_dueling_bench_version_is_a_floor() -> None:
    assert not is_dueling_bench_version(DUELING_MIN_BENCH_VERSION - 1)
    assert is_dueling_bench_version(DUELING_MIN_BENCH_VERSION)
    assert is_dueling_bench_version(DUELING_MIN_BENCH_VERSION + 7)


def test_season_vectors() -> None:
    seasons = _load("season_vectors.json")["seasons"]
    assert seasons
    for v in seasons:
        secret = bytes.fromhex(v["secret_hex"])
        assert season_commitment(v["season_index"], secret) == v["commitment"]
        seed = season_seed(v["season_index"], secret, v["anchor_block_hash"])
        assert seed == v["season_seed"]
        for s in v["slice_seeds"]:
            assert slice_seed(seed, s["run_seed"], s["column_id"]) == s["slice_seed"]


@pytest.mark.parametrize("secret", [b"", b"\x00" * 31, b"\x00" * 33])
def test_season_refuses_a_bad_secret(secret: bytes) -> None:
    with pytest.raises(ValueError):
        season_commitment(1, secret)
    with pytest.raises(ValueError):
        season_seed(1, secret, "0x" + "ab" * 32)


@pytest.mark.parametrize(
    "block", ["", "0x1234", "0x" + "zz" * 32, "ab" * 33, "ab " * 31 + "ab"]
)
def test_season_seed_refuses_a_bad_anchor(block: str) -> None:
    with pytest.raises(ValueError):
        season_seed(1, b"\x01" * 32, block)


@pytest.mark.parametrize("bad", [26119.0, True, "26119"])
def test_season_and_run_seed_must_be_real_ints(bad: object) -> None:
    with pytest.raises(ValueError):
        season_commitment(bad, b"\x01" * 32)  # type: ignore[arg-type]
    with pytest.raises(ValueError):
        season_seed(bad, b"\x01" * 32, "0x" + "ab" * 32)  # type: ignore[arg-type]
    seed = season_seed(1, b"\x01" * 32, "0x" + "ab" * 32)
    with pytest.raises(ValueError):
        slice_seed(seed, bad, "c0")  # type: ignore[arg-type]


def test_column_with_no_cases_has_zero_sums() -> None:
    with pytest.raises(ValidationError):
        DuelingColumnAggregate(column_id="c0", owner_key="", n=0, sum=1.0, sum_sq=0.0)
    with pytest.raises(ValidationError):
        DuelingColumnAggregate(column_id="c0", owner_key="", n=0, sum=0.0, sum_sq=1.0)
    empty = DuelingColumnAggregate(column_id="c0", owner_key="", n=0, sum=0, sum_sq=0)
    assert empty.mean() == 0


def test_season_index_must_be_u64() -> None:
    with pytest.raises(ValueError):
        season_commitment(-1, b"\x01" * 32)
    with pytest.raises(ValueError):
        season_commitment(1 << 64, b"\x01" * 32)


def test_slice_seed_refuses_bad_inputs() -> None:
    seed = season_seed(1, b"\x01" * 32, "0x" + "ab" * 32)
    for bad_seed in ["", seed.upper(), seed[:63], "0x" + seed[2:]]:
        with pytest.raises(ValueError):
            slice_seed(bad_seed, 1, "c0")
    for bad_run in [-1, 1 << 63]:
        with pytest.raises(ValueError):
            slice_seed(seed, bad_run, "c0")
    with pytest.raises(ValueError):
        slice_seed(seed, 1, "")


def test_composite_vectors_bit_for_bit() -> None:
    vectors = _load("dueling_composite_vectors.json")["composites"]
    assert len(vectors) >= 10
    for v in vectors:
        columns = [DuelingColumnAggregate.model_validate(c) for c in v["columns"] or []]
        mask = frozenset(v["mask"] or [])
        got = dueling_composite(v["datagen_raw"], v["datagen_gate"], columns, mask)
        assert _bits(got) == _bits(v["composite"]), v["name"]
        se = dueling_composite_stderr(
            v["datagen_stderr"], v["datagen_gate"], columns, mask
        )
        assert _bits(se) == _bits(v["composite_stderr"]), v["name"]


