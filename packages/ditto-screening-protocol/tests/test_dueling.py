def test_report_self_and_pair_masks() -> None:
    report = DuelingReport.model_validate(_report())
    # Self-mask drops c0: 0.6 x 0.8 + 0.1 x (0.25 + 1 + 0.5 + 0).
    assert report.self_composite() == pytest.approx(0.6 * 0.8 + 0.1 * 1.75)
    # Pair-mask with o3 also drops c2; its weight returns to the datagen half.
    assert report.composite(frozenset({"coldkey:o1", "coldkey:o3"})) == pytest.approx(
        0.7 * 0.8 + 0.1 * 0.75
    )
    # The empty owner key is never masked.
    assert report.composite(frozenset({""})) == report.composite(frozenset())


def test_report_is_strict() -> None:
    with pytest.raises(ValidationError):
        DuelingReport.model_validate(_report(column_weight=0.2))
    with pytest.raises(ValidationError):
        DuelingReport.model_validate(_report(columns=_report()["columns"][:4]))
    renamed = _report()["columns"]
    renamed[4] = {**renamed[4], "column_id": "c7"}
    with pytest.raises(ValidationError):
        DuelingReport.model_validate(_report(columns=renamed))
    dup = _report()["columns"]
    dup[1] = {**dup[1], "column_id": "c0"}
    with pytest.raises(ValidationError):
        DuelingReport.model_validate(_report(columns=dup))
    # Additive fields are ignored, not refused (rolling upgrades).
    assert DuelingReport.model_validate(
        _report(extra=1)
    ) == DuelingReport.model_validate(_report())
    with pytest.raises(ValidationError):
        DuelingReport.model_validate(_report(datagen_raw=float("nan")))
    with pytest.raises(ValidationError):
        DuelingColumnAggregate(
            column_id="c3",
            owner_key="coldkey:x",
            n=1,
            sum=1,
            sum_sq=1,
            substituted=True,
        )


def test_column_pin_ownership() -> None:
    base = {
        "column_id": "c0",
        "submission_id": "default",
        "miner_hotkey": _HOTKEY,
        "owner_key": "",
        "tree_sha256": "cd" * 32,
        "grading_bench_version": 15,
        "public_default": True,
    }
    assert DuelingColumnPin.model_validate(base).owner_key == ""
    with pytest.raises(ValidationError):
        DuelingColumnPin.model_validate({**base, "owner_key": "coldkey:x"})
    with pytest.raises(ValidationError):
        DuelingColumnPin.model_validate({**base, "public_default": False})
    pin = DuelingColumnPin.model_validate(
        {
            **base,
            "public_default": False,
            "owner_key": "coldkey:x",
            "source_sha256": "ef" * 32,
        }
    )
    assert pin.source_sha256 == "ef" * 32


_SCORER_REPORT_GOLDEN = (
    _MONOREPO_ROOT
    / "services/dittobench-api/cmd/dittobench-api/testdata/dueling_report_golden.json"
)


def test_scorer_report_golden_round_trips() -> None:
    """The ``details.dueling`` block dittobench-api emits parses as a
    :class:`DuelingReport` with exactly its fields, and refolds bit for bit.

    The golden is written by ``go test ./cmd/dittobench-api -run
    TestDuelingReportGolden -update-dueling-golden``.
    """
    golden = json.loads(_SCORER_REPORT_GOLDEN.read_text())
    details = golden["details"]
    assert set(details) == set(DuelingReport.model_fields)
    for column in details["columns"]:
        assert set(column) == set(DuelingColumnAggregate.model_fields)
    report = DuelingReport.model_validate(details)
    assert report.model_dump(mode="json") == details
    assert _bits(report.self_composite()) == _bits(golden["self_composite"])
    assert _bits(report.composite(frozenset(golden["pair_mask"]))) == _bits(
        golden["pair_composite"]
    )
    stderr = dueling_composite_stderr(
        golden["datagen_stderr"],
        report.datagen_gate,
        report.columns,
        frozenset({report.owner_key}),
    )
    assert _bits(stderr) == _bits(report.composite_stderr)
    assert _bits(stderr) == _bits(golden["composite_stderr"])
