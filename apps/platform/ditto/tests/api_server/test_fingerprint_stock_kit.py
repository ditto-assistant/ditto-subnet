"""Stock-kit file exclusion: the 2026-07-20 copy-hold regressions.

Two real holds from the same afternoon, both opened by the lexical channel with
the same 21 byte-identical starter-kit files between the pair, and only one of
them a copy:

* FALSE POSITIVE — ``bf57c7ea`` (FOREVER v3) held against ``6334962e``
  (F1rst v1), different coldkeys. Recorded evidence: ``jaccard 0.703,
  containment 0.954``. The one file carrying miner work, ``src/baseline.rs``,
  was *not* shared (0.9062 similar, +231/-11 against a kit file both forked);
  prompt jaccard was 0.320. What crossed the 0.95 containment bar was the
  unmodified kit itself — ``Cargo.lock`` (5,439 lines) and
  ``fixtures/models/cross-encoder-vocab.txt`` (30,522 lines) alone are ~366KB of
  identical text neither miner wrote. Window subtraction did not neutralize it
  because both miners forked a kit revision the shingle bundles do not contain.
* TRUE POSITIVE — ``16eddfaf`` (beking-v1) against ``81266c17`` (gggggggg v3),
  different coldkeys, 67 minutes apart. Recorded evidence: ``jaccard 0.969,
  containment 0.988``, prompt jaccard 1.000. Same 21 identical kit files, but
  here ``src/baseline.rs`` is itself near-verbatim: 0.9943 similar, +6/-10 out of
  1,408 lines.

The fixtures below reproduce that shape: identical kit content on both sides,
and the discriminator moved entirely into the authored file. The kit revision is
installed in the *digest* set but deliberately kept out of the *shingle* corpus
(except the file both miners edited, whose kit ancestor the corpus does contain —
that is the case window subtraction already handled), which is exactly the
production configuration that produced the false positive.
"""

