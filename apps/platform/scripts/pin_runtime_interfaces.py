"""Regenerate ``ditto/chain/audited_runtime_interfaces.py`` from live metadata.

Each pin names an audited release and a Finney block that ran it. The script
reads that block's runtime metadata, checks the ``:code`` hash is the expected
audited artifact, and writes the consumed-interface fingerprints for every
surface. Review the diff before committing; see
docs/source-runtime-interface.md.

Usage::

    uv run python scripts/pin_runtime_interfaces.py \\
      --url wss://archive.chain.opentensor.ai:443 --write
"""

from __future__ import annotations

import argparse
import asyncio
import subprocess
import sys
from pathlib import Path

from ditto.chain.runtime_interface import (
    SOURCE_EMISSION_SURFACE,
    TREASURY_RECEIPT_SURFACE,
    RuntimeInterface,
    metadata_at,
    runtime_call_digests,
    runtime_interface,
)

# (release, Finney block, expected :code hash). Both are audited artifacts in
# AUDITED_RUNTIME_CODE_HASHES and AUDITED_COLLECTOR_RECEIPT_HASHES.
PINS = (
    (
        "v473",
        9220000,
        "0x7773f5c0a6d6e9ea9ff347edcc491246eec08a5cf441d964ee96f40d7fa65a08",
    ),
    (
        "v478",
        9280000,
        "0x7e722b3aa5c9192c98665a5d65fa91364bf9055e21fc90efce6d59bf4ef414e1",
    ),
    (
        "v482",
        9336443,
        "0x37d83888085e2f1b7c9c36c1341cfb6c0d6689f8efd6e0c6128e3666eb5d8b62",
    ),
    (
        "v483",
        9346596,
        "0x99856ec64a61eb8011999a803bd336979512275214a173fea583abd5c89952d2",
    ),
)
# The runtime the treasury signer's cold-signed policy binds; its per-call
# digests are the baseline the treasury runtime report compares against.
TREASURY_CALL_BASELINE = "v483"
TARGET = (
    Path(__file__).resolve().parents[1] / "ditto/chain/audited_runtime_interfaces.py"
)

HEADER = '''"""Consumed-interface fingerprints of audited Subtensor runtimes.

Generated by scripts/pin_runtime_interfaces.py from live Finney metadata at a
block of each named audited runtime. A runtime whose consumed interface digest
appears here is admitted for reading without a per-release artifact audit.
See docs/source-runtime-interface.md before adding an entry.
"""

from __future__ import annotations

from ditto.chain.runtime_interface import RuntimeInterface

'''


def _interface(interface: RuntimeInterface) -> str:
    pad = " " * 16
    entries = "".join(
        f'{pad}"{name}": (\n{pad}    "{digest}"\n{pad}),\n'
        for name, digest in sorted(interface.entries.items())
    )
    return (
        "        RuntimeInterface(\n"
        f'            digest="{interface.digest}",\n'
        f"            has_epoch_consensus={interface.has_epoch_consensus},\n"
        "            entries={\n"
        f"{entries}"
        "            },\n"
        "        ),\n"
    )


def _pins(
    name: str, comment: str, rows: list[tuple[str, int, str, RuntimeInterface]]
) -> str:
    body, seen = "", set()
    for release, block, code, interface in rows:
        # Releases with identical surfaces collapse to the first one.
        if interface.digest in seen:
            continue
        seen.add(interface.digest)
        body += (
            f"    # {release}: runtime {code}\n"
            f"    # at Finney block {block}.\n"
            f'    "{interface.digest}": (\n'
            f'        "{release}",\n'
            f"{_interface(interface)}"
            "    ),\n"
        )
    return (
        f"# {comment}\n{name}: dict[str, tuple[str, RuntimeInterface]] = {{\n{body}}}\n"
    )


async def render(url: str) -> str:
    from async_substrate_interface import AsyncSubstrateInterface

    if TREASURY_CALL_BASELINE not in {release for release, _, _ in PINS}:
        raise SystemExit(
            f"PINS does not contain TREASURY_CALL_BASELINE {TREASURY_CALL_BASELINE}"
        )

    source, treasury = [], []
    calls: dict[str, str] = {}
    async with AsyncSubstrateInterface(url=url) as substrate:
        for release, block, expected in PINS:
            at = await substrate.get_block_hash(block)
            code = (
                await substrate.rpc_request(
                    "state_getStorageHash", ["0x3a636f6465", at]
                )
            )["result"]
            if code != expected:
                raise SystemExit(f"{release} block {block} runs {code}, not {expected}")
            metadata = await metadata_at(substrate, at)
            source.append(
                (
                    release,
                    block,
                    code,
                    runtime_interface(metadata, SOURCE_EMISSION_SURFACE),
                )
            )
            treasury.append(
                (
                    release,
                    block,
                    code,
                    runtime_interface(metadata, TREASURY_RECEIPT_SURFACE),
                )
            )
            if release == TREASURY_CALL_BASELINE:
                calls = runtime_call_digests(metadata)
    # Short digests fit one line; ruff format cannot split a long call name's
    # row, so parenthesize the value whenever the row would exceed 88 columns.
    call_rows = "".join(
        f'        "{call}": "{digest}",\n'
        if len(f'        "{call}": "{digest}",') <= 88
        else f'        "{call}": (\n            "{digest}"\n        ),\n'
        for call, digest in calls.items()
    )
    return (
        HEADER
        + _pins(
            "AUDITED_RUNTIME_INTERFACES",
            "Source attribution: digest -> (audited release, consumed interface).",
            source,
        )
        + "\n"
        + _pins(
            "TREASURY_RECEIPT_INTERFACES",
            "Treasury receipt reading: digest -> (audited release, interface).",
            treasury,
        )
        + "\n# Per-call digests of the runtime the treasury signer policy binds.\n"
        + "TREASURY_CALL_BASELINE: tuple[str, dict[str, str]] = (\n"
        + f'    "{TREASURY_CALL_BASELINE}",\n    {{\n{call_rows}    }},\n)\n'
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--url", default="wss://archive.chain.opentensor.ai:443")
    parser.add_argument("--write", action="store_true", help="overwrite the module")
    args = parser.parse_args()
    module = asyncio.run(render(args.url))
    if not args.write:
        sys.stdout.write(module)
        return 0
    TARGET.write_text(module)
    subprocess.run(["uv", "run", "ruff", "format", str(TARGET)], check=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
